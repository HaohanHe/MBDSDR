@lru_cache(maxsize=1)
def _parse_graph():
    """由内嵌常数表构造 Tanner 图。

    返回 (check_vars, var_checks)，均为 0-based 索引列表。
    """
    var_checks: list[list[int]] = [[] for _ in range(_N)]
    for v in range(_N):
        var_checks[v] = [_FT8_MN[3 * v + k] - 1 for k in range(3)]
    check_vars: list[list[int]] = []
    for c in range(_M):
        n = _FT8_NRW[c]
        check_vars.append([_FT8_NM[7 * c + i] - 1 for i in range(n)])
    return check_vars, var_checks


def ldpc_bp_decode(llr: list[float], max_iter: int = 25) -> tuple[list[int], int]:
    """归一化 min-sum BP 译码。

    输入：174 个信道 LLR（正=偏向 0，负=偏向 1）。
    输出：(硬判决码字 0/1, 实际迭代次数)。

    早停判据：每轮统计未满足校验数；若连续 5 轮不再下降、已迭代 >=10 轮且
    残差仍 >15，则提前退出。该判据只省无效迭代，不改变"全部校验满足即收敛"
    的正确译码路径。
    """
    check_vars, var_checks = _parse_graph()

    # 初始化：变量→校验消息 = 信道 LLR
    q: dict[tuple[int, int], float] = {}
    for c, vs in enumerate(check_vars):
        for v in vs:
            q[(c, v)] = llr[v]

    decoded = [0] * _N
    nclast: int | None = None
    no_improve = 0
    for it in range(max_iter):
        # 校验→变量：归一化 min-sum（归一化因子 0.75）
        r: dict[tuple[int, int], float] = {}
        for c, vs in enumerate(check_vars):
            for v in vs:
                prod_sign = 1.0
                min_abs = float("inf")
                for u in vs:
                    if u != v:
                        x = q[(c, u)]
                        prod_sign *= 1.0 if x >= 0 else -1.0
                        min_abs = min(min_abs, abs(x))
                r[(c, v)] = prod_sign * min_abs * 0.75
        # 变量→校验 + 硬判决
        for v in range(_N):
            total = llr[v] + sum(r[(c, v)] for c in var_checks[v])
            decoded[v] = 0 if total >= 0 else 1
            for c in var_checks[v]:
                q[(c, v)] = total - r[(c, v)]
        # 统计未满足校验数
        ncheck = sum(
            1 for c in range(_M)
            if sum(decoded[v] for v in check_vars[c]) % 2 != 0
        )
        if ncheck == 0:
            return decoded, it + 1
        if nclast is not None:
            if ncheck - nclast < 0:
                no_improve = 0
            else:
                no_improve += 1
            if no_improve >= 5 and it >= 10 and ncheck > 15:
                break
        nclast = ncheck
    return decoded, it + 1


