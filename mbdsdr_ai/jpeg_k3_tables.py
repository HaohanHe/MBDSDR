def build_k3_tables() -> Dict[Tuple[str, int], HuffmanTable]:
    """构造 Annex K.3 四张硬编码表。

    返回 ``{("DC"|"AC", 0=luma/1=chroma): HuffmanTable}``，与
    ``lrpt_huffman.HuffmanTable`` 的 (cls, table_id) 定位口径一致，
    可直接注入 JpegHeader 的 dc_tables/ac_tables。
    """
    tables: Dict[Tuple[str, int], HuffmanTable] = {}
    tables[("DC", 0)] = HuffmanTable(list(K3_DC_LUMA_BITS),
                                     list(K3_DC_LUMA_VALS), "DC", 0)
    tables[("DC", 1)] = HuffmanTable(list(K3_DC_CHROMA_BITS),
                                     list(K3_DC_CHROMA_VALS), "DC", 1)
    tables[("AC", 0)] = HuffmanTable(list(K3_AC_LUMA_BITS),
                                     list(K3_AC_LUMA_VALS), "AC", 0)
    tables[("AC", 1)] = HuffmanTable(list(K3_AC_CHROMA_BITS),
                                     list(K3_AC_CHROMA_VALS), "AC", 1)
    return tables


def k3_tables_for_component(component_index: int) -> Dict[Tuple[str, int], HuffmanTable]:
    """按 JPEG 分量序号取该分量使用的表（0=亮度，其余=色度）。

    Meteor LRPT 的 SOF 采样因子与 RFC 2435 Type 0 的口径一致：
    分量 0 用 DC0/AC0，分量 1、2 用 DC1/AC1。
    """
    all_tables = build_k3_tables()
    slot = 0 if component_index == 0 else 1
    return {("DC", slot): all_tables[("DC", slot)],
            ("AC", slot): all_tables[("AC", slot)]}
